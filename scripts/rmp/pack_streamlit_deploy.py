#!/usr/bin/env python3
"""Copy slim runtime artifacts into data/deploy/ for Streamlit Cloud / Docker."""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEPLOY = ROOT / "data" / "deploy"

WASATCH_SRC = ROOT / "data" / "processed" / "wasatch_residential_day"
GRID_SRC = ROOT / "data" / "processed" / "grid_pace"
RAW_SRC = ROOT / "data" / "raw" / "rmp" / "hourly"
MODELS_SRC = ROOT / "models"

METER_KEYS = ("342856918_sfh", "50752799_casita")
HERO_DATES = ("2026-07-27", "2026-10-25")


def _copy_file(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def _copy_tree_files(src: Path, dst: Path, pattern: str = "**/*") -> int:
    n = 0
    if not src.is_dir():
        return 0
    for path in src.glob(pattern):
        if not path.is_file():
            continue
        rel = path.relative_to(src)
        _copy_file(path, dst / rel)
        n += 1
    return n


def main() -> int:
    if not (WASATCH_SRC / "all_days.parquet").is_file():
        print("Missing wasatch all_days.parquet — run aggregate_wasatch_day.py", file=sys.stderr)
        return 1
    if not (MODELS_SRC / "wasatch_demand_hgb.pkl").is_file():
        print("Missing models — run train_demand_forecast.py", file=sys.stderr)
        return 1

    if DEPLOY.exists():
        shutil.rmtree(DEPLOY)
    DEPLOY.mkdir(parents=True)

    _copy_file(
        WASATCH_SRC / "all_days.parquet",
        DEPLOY / "processed" / "wasatch_residential_day" / "all_days.parquet",
    )
    for extra in WASATCH_SRC.glob("*.json"):
        _copy_file(extra, DEPLOY / "processed" / "wasatch_residential_day" / extra.name)

    grid_n = 0
    if GRID_SRC.is_dir():
        for day_dir in sorted(GRID_SRC.iterdir()):
            if not day_dir.is_dir():
                continue
            for name in ("demand.parquet", "fuel_mix.parquet", "source.txt", "cache_version.txt"):
                src = day_dir / name
                if src.is_file():
                    _copy_file(
                        src,
                        DEPLOY / "processed" / "grid_pace" / day_dir.name / name,
                    )
                    grid_n += 1

    meter_n = 0
    for key in METER_KEYS:
        src_dir = RAW_SRC / key
        if not src_dir.is_dir():
            print(f"warn: missing meter folder {key}", file=sys.stderr)
            continue
        # Prefer hero days + a thin recent slice so §3 never empties
        wanted = set(HERO_DATES)
        all_days = sorted(p.stem for p in src_dir.glob("*.json"))
        wanted.update(all_days[-14:])
        for day in wanted:
            src = src_dir / f"{day}.json"
            if src.is_file():
                _copy_file(src, DEPLOY / "raw" / "rmp" / "hourly" / key / src.name)
                meter_n += 1

    for name in (
        "wasatch_demand_hgb.pkl",
        "pace_demand_hgb.pkl",
        "model_meta.json",
    ):
        src = MODELS_SRC / name
        if src.is_file():
            _copy_file(src, DEPLOY / "models" / name)

    (DEPLOY / "README.md").write_text(
        "# Slim Streamlit deploy pack\n\n"
        "Generated by `scripts/rmp/pack_streamlit_deploy.py`.\n"
        "App `lib/paths.py` prefers this tree when `all_days.parquet` is present.\n"
    )

    size_mb = sum(p.stat().st_size for p in DEPLOY.rglob("*") if p.is_file()) / 1e6
    print(
        f"Wrote {DEPLOY} · {size_mb:.1f} MB · "
        f"grid files={grid_n} · meter days={meter_n}"
    )
    for hero in HERO_DATES:
        ok = (DEPLOY / "processed" / "grid_pace" / hero / "demand.parquet").is_file()
        print(f"  hero {hero}: grid={'ok' if ok else 'MISSING'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
